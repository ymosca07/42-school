#include "../philo.h"

void	tmp_error(char **tmp)
{
	int	n;

	n = 0;
	while (tmp[n])
	{
		free(tmp[n]);
		n++;
	}
	free(tmp);
	printf("Tmp error\n");
	exit(1);
}
